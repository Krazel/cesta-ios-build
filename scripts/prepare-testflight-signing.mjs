import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { asc } from './asc-client.mjs';
const directory = process.argv[2];
assert(directory, 'A private signing output directory is required');
const config = JSON.parse(fs.readFileSync('store/testflight.json'));
const bundle = (await asc('GET', `/v1/bundleIds/${config.bundleResourceId}`)).data;
assert.equal(bundle.attributes.identifier, config.bundleId);
const certificate = (await asc('GET', '/v1/certificates/2K3G3RTCS5')).data;
assert.equal(certificate.attributes.certificateType, 'DISTRIBUTION');
assert(Date.parse(certificate.attributes.expirationDate) > Date.now());
const profiles = (await asc('GET', `/v1/bundleIds/${bundle.id}/profiles?limit=200`)).data;
const name = 'Cesta App Store 2026-09-05';
let profile = profiles.find(p => p.attributes.name === name && p.attributes.profileState === 'ACTIVE');
if (profile) profile = (await asc('GET', `/v1/profiles/${profile.id}`)).data;
else profile = (await asc('POST', '/v1/profiles', {data:{type:'profiles',attributes:{name,profileType:'IOS_APP_STORE'},relationships:{bundleId:{data:{type:'bundleIds',id:bundle.id}},certificates:{data:[{type:'certificates',id:certificate.id}]}}}})).data;
fs.mkdirSync(directory,{recursive:true});
fs.writeFileSync(path.join(directory,'Cesta-App-Store.mobileprovision'),Buffer.from(profile.attributes.profileContent,'base64'));
const state = {bundleIdentifier:config.bundleId,bundleId:bundle.id,teamId:config.teamId,certificateId:certificate.id,profileId:profile.id,profileName:profile.attributes.name,profileUuid:profile.attributes.uuid,expirationDate:profile.attributes.expirationDate};
fs.writeFileSync(path.join(directory,'signing-resource-state.json'),JSON.stringify(state,null,2)+'\n');
console.log(JSON.stringify(state));
